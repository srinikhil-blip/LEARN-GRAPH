"""
LearnGraph — Curriculum Router
Serves comprehensive educational catalog data for the Course Library.
Loads from backend/data/curriculum_catalog.json (generated by scripts/build_curriculum_catalog.js).
"""

import json
import os
from functools import lru_cache
from typing import Any, Dict, List, Optional

from fastapi import APIRouter, Query, HTTPException

router = APIRouter(prefix="/curriculum", tags=["Curriculum"])

# ── Catalog loader ──────────────────────────────────────────────────────────

CATALOG_PATH = os.path.join(
    os.path.dirname(__file__),
    "..",
    "..",
    "..",
    "..",
    "..",
    "backend",
    "data",
    "curriculum_catalog.json",
)


@lru_cache(maxsize=1)
def _load_catalog() -> Dict[str, Any]:
    """Load and cache the curriculum catalog JSON once at startup."""
    abs_path = os.path.normpath(CATALOG_PATH)
    if not os.path.exists(abs_path):
        # Try relative to CWD (when running from project root)
        alt_path = os.path.join("backend", "data", "curriculum_catalog.json")
        if os.path.exists(alt_path):
            abs_path = alt_path
        else:
            return {"courses": [], "levels": [], "programs": [], "competitiveExams": []}
    with open(abs_path, "r", encoding="utf-8") as f:
        return json.load(f)


def get_all_courses() -> List[Dict[str, Any]]:
    return _load_catalog().get("courses", [])


# ── Routes ───────────────────────────────────────────────────────────────────


@router.get("", summary="Curriculum catalog overview")
async def get_curriculum_overview():
    """Return catalog metadata: version, levels, programs summary."""
    catalog = _load_catalog()
    return {
        "version": catalog.get("version"),
        "updatedAt": catalog.get("updatedAt"),
        "totalCourses": catalog.get("totalCourses"),
        "levels": catalog.get("levels", []),
        "programs": catalog.get("programs", []),
    }


@router.get("/levels", summary="List education levels")
async def get_levels():
    return _load_catalog().get("levels", [])


@router.get("/programs", summary="List academic programs")
async def get_programs(level_id: Optional[str] = Query(None)):
    programs = _load_catalog().get("programs", [])
    if level_id:
        programs = [p for p in programs if p.get("levelId") == level_id]
    return programs


@router.get("/subjects", summary="List subjects")
async def get_subjects(tier: Optional[str] = Query(None)):
    courses = get_all_courses()
    if tier:
        courses = [c for c in courses if c.get("tier") == tier]
    subjects = sorted(set(c.get("subject", "") for c in courses if c.get("subject")))
    return [{"name": s} for s in subjects]


@router.get("/classes", summary="List school class grades")
async def get_classes():
    courses = get_all_courses()
    school_courses = [c for c in courses if c.get("tier") == "School"]
    grades = sorted(set(c.get("gradeOrYear", "") for c in school_courses if c.get("gradeOrYear")))
    return grades


@router.get("/chapters", summary="Get chapters for a course")
async def get_chapters(course_id: Optional[str] = Query(None)):
    if not course_id:
        return []
    courses = get_all_courses()
    course = next((c for c in courses if c.get("id") == course_id), None)
    if not course:
        return []
    return course.get("chapters", [])


@router.get("/topics", summary="Get lessons/topics for a chapter")
async def get_topics(
    course_id: Optional[str] = Query(None),
    chapter_id: Optional[str] = Query(None),
):
    if not course_id:
        return []
    courses = get_all_courses()
    course = next((c for c in courses if c.get("id") == course_id), None)
    if not course:
        return []
    if chapter_id:
        chapter = next(
            (ch for ch in course.get("chapters", []) if ch.get("id") == chapter_id), None
        )
        return chapter.get("lessons", []) if chapter else []
    # Return all lessons across all chapters
    all_lessons = []
    for ch in course.get("chapters", []):
        all_lessons.extend(ch.get("lessons", []))
    return all_lessons


@router.get("/search", summary="Search curriculum catalog")
async def search_curriculum(
    q: Optional[str] = Query(None),
    tier: Optional[str] = Query(None),
    subject: Optional[str] = Query(None),
    grade: Optional[str] = Query(None),
    page: int = Query(1, ge=1),
    page_size: int = Query(20, ge=1, le=100),
):
    courses = get_all_courses()

    if tier:
        courses = [c for c in courses if c.get("tier") == tier]
    if subject:
        courses = [c for c in courses if c.get("subject") == subject]
    if grade:
        courses = [c for c in courses if grade in (c.get("gradeOrYear") or "")]

    if q:
        q_lower = q.lower()
        def matches(c: Dict) -> bool:
            return any(
                q_lower in str(c.get(field, "")).lower()
                for field in ["title", "subject", "description", "gradeOrYear", "instructor"]
            ) or any(
                q_lower in item.lower()
                for item in (c.get("syllabus") or [])
                if isinstance(item, str)
            )
        courses = [c for c in courses if matches(c)]

    total = len(courses)
    start = (page - 1) * page_size
    paginated = courses[start : start + page_size]

    return {
        "items": paginated,
        "total": total,
        "page": page,
        "pageSize": page_size,
        "hasMore": start + page_size < total,
    }


@router.get("/competitive-exams", summary="List competitive exam programs")
async def get_competitive_exams():
    return _load_catalog().get("competitiveExams", [])
